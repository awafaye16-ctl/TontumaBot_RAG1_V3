def reranker_chunks(question, candidats_ids, top_k=5):
    if not candidats_ids:
        return []
    if not RERANKER_OK:
        return candidats_ids[:top_k]

    textes = [df_chunks.loc[df_chunks["chunk_id"] == cid, "text"].values[0] for cid in candidats_ids]
    paires = [[question, texte] for texte in textes]
    scores = reranker.predict(paires)

    ordre = np.argsort(-scores)
    return [candidats_ids[i] for i in ordre[:top_k]], [float(scores[i]) for i in ordre[:top_k]]


