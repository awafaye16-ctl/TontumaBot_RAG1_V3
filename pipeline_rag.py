"""## 4. Découpage en morceaux (chunks)

Priorité au découpage par section structurée ; le texte hors section passe par le text splitter à taille fixe.
"""

def decouper_par_taille(texte, chunk_size=CHUNK_SIZE, chunk_overlap=CHUNK_OVERLAP):
    if LANGCHAIN_OK:
        return splitter.split_text(texte)
    # Repli manuel si langchain n'est pas installé
    morceaux = []
    debut = 0
    while debut < len(texte):
        fin = debut + chunk_size
        morceaux.append(texte[debut:fin])
        debut += chunk_size - chunk_overlap
    return morceaux


def decouper_intelligemment(texte, document, page):
    """Découpe par section structurée si détectée, sinon par taille fixe."""
    sections = MOTIF_SECTION.split(texte)
    chunks = []

    if len(sections) > 1:
        # sections[0] = texte avant la 1ère section (souvent du bruit d'en-tête)
        # puis alternance [titre_section, contenu, titre_section, contenu, ...]
        i = 1
        while i < len(sections) - 1:
            titre = sections[i].strip()
            contenu = sections[i + 1].strip()
            texte_complet = f"{titre}\n{contenu}"
            if len(texte_complet) > CHUNK_SIZE * 1.5:
                for sous_morceau in decouper_par_taille(texte_complet):
                    chunks.append({"section": titre, "text": sous_morceau})
            else:
                chunks.append({"section": titre, "text": texte_complet})
            i += 2
    else:
        # Pas de section structurée détectée -> découpage par taille uniquement
        for morceau in decouper_par_taille(texte):
            chunks.append({"section": f"{document} p.{page}", "text": morceau})

    return chunks


