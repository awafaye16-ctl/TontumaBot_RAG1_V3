def charger_pdf(chemin):
    from pypdf import PdfReader
    reader = PdfReader(chemin)
    pages = []
    for i, page in enumerate(reader.pages):
        texte = page.extract_text() or ""
        pages.append({"page": i + 1, "text": texte})
    return pages


def charger_txt(chemin):
    with open(chemin, "r", encoding="utf-8") as f:
        return [{"page": 1, "text": f.read()}]


def charger_docx(chemin):
    from docx import Document
    doc = Document(chemin)
    texte = "\n".join(p.text for p in doc.paragraphs)
    return [{"page": 1, "text": texte}]


def charger_document(chemin):
    """Charge un fichier selon son extension et retourne une liste de pages {page, text}."""
    chemin = Path(chemin)
    extension = chemin.suffix.lower()

    if extension == ".pdf":
        pages = charger_pdf(chemin)
    elif extension == ".txt":
        pages = charger_txt(chemin)
    elif extension == ".docx":
        pages = charger_docx(chemin)
    else:
        raise ValueError(f"Extension non supportée : {extension} (attendu : .pdf, .txt, .docx)")

    for p in pages:
        p["document"] = chemin.name
        p["source"] = str(chemin)
    return pages


