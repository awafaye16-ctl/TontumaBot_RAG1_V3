    prompt = construire_prompt(contexte, question)

    t0 = time.perf_counter()
    reponse = generer_reponse(prompt)
    temps_generation_ms = (time.perf_counter() - t0) * 1000

    return {
        "question": question, "reponse": reponse, "contexte": contexte,
        "chunk_ids": resultat_retrieval["chunk_ids"],
        "latences": {**resultat_retrieval["latences"], "generation_ms": round(temps_generation_ms, 1)},
    }


