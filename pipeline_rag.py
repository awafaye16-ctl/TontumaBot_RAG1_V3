def recherche_vectorielle(question, top_k=10):
    """Recherche dense via ChromaDB. Retourne une liste de (chunk_id, score) triée par pertinence."""
    embedding_question = embedder.encode([question], normalize_embeddings=True)[0]
    resultats = collection.query(query_embeddings=[embedding_question.tolist()], n_results=top_k)
    # ChromaDB retourne une distance (plus bas = plus proche) ; on la convertit en score de similarité
    ids = resultats["ids"][0]
    distances = resultats["distances"][0]
    scores = [1 - d for d in distances]  # approximation cosine similarity à partir de la distance
    return list(zip(ids, scores))


def recherche_bm25(question, top_k=10):
    """Recherche lexicale BM25. Retourne une liste de (chunk_id, score) triée par pertinence."""
    scores = bm25.get_scores(tokeniser_simple(question))
    indices_tries = np.argsort(-scores)[:top_k]
    return [(df_chunks.iloc[i]["chunk_id"], float(scores[i])) for i in indices_tries]


