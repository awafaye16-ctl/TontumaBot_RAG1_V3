"""## 12. Reranking

Cross-encoder qui réévalue précisément la pertinence question/chunk (plus lent mais plus fin que la similarité d'embeddings seule).
"""

RERANKER_MODEL = "cross-encoder/ms-marco-MiniLM-L-6-v2"

