"""## 13. Fonction complète de récupération (Top-K chunks)

Assemble toutes les étapes précédentes en une seule fonction réutilisable.
"""

def recuperer_chunks(question, top_k_hybride=10, top_k_mmr=5, top_k_final=5, seuil_filtre=SEUIL_SCORE_MIN):
    t0 = time.perf_counter()
    resultats_fusionnes = recherche_hybride(question, top_k=top_k_hybride)
    t_hybride = time.perf_counter() - t0

    ids_fusionnes = [cid for cid, _ in resultats_fusionnes]

    t0 = time.perf_counter()
    ids_mmr = mmr(question, ids_fusionnes, top_k=top_k_mmr)
    t_mmr = time.perf_counter() - t0

    t0 = time.perf_counter()
    ids_filtres = filtrer_chunks(ids_mmr, resultats_fusionnes, seuil=seuil_filtre)
    t_filtre = time.perf_counter() - t0

    t0 = time.perf_counter()
    if RERANKER_OK:
        ids_finaux, scores_finaux = reranker_chunks(question, ids_filtres, top_k=top_k_final)
    else:
        ids_finaux = ids_filtres[:top_k_final]
        scores_finaux = [None] * len(ids_finaux)
    t_rerank = time.perf_counter() - t0

    chunks_textes = [df_chunks.loc[df_chunks["chunk_id"] == cid, "text"].values[0] for cid in ids_finaux]

    latences = {
        "hybride_ms": round(t_hybride * 1000, 1), "mmr_ms": round(t_mmr * 1000, 1),
        "filtre_ms": round(t_filtre * 1000, 1), "rerank_ms": round(t_rerank * 1000, 1),
    }
    latences["retrieval_total_ms"] = round(sum(latences.values()), 1)

    return {
        "chunk_ids": ids_finaux, "textes": chunks_textes, "scores": scores_finaux, "latences": latences,
    }


