"""## 9. Fusion

Fusion des deux classements (dense + BM25) par **Reciprocal Rank Fusion (RRF)** — combine les rangs plutôt que les scores bruts, qui ne sont pas sur la même échelle entre BM25 et cosine similarity.
"""

def fusion_rrf(liste_resultats, k=60):
    """
    Reciprocal Rank Fusion : combine plusieurs classements (chacun une liste de (id, score)
    triée par pertinence décroissante) en un score fusionné unique par id.
    """
    scores_fusionnes = {}
    for resultats in liste_resultats:
        for rang, (chunk_id, _) in enumerate(resultats, start=1):
            scores_fusionnes[chunk_id] = scores_fusionnes.get(chunk_id, 0) + 1 / (k + rang)
    return sorted(scores_fusionnes.items(), key=lambda x: -x[1])


def recherche_hybride(question, top_k=10):
    resultats_dense = recherche_vectorielle(question, top_k=top_k)
    resultats_bm25 = recherche_bm25(question, top_k=top_k)
    fusionnes = fusion_rrf([resultats_dense, resultats_bm25])
    return fusionnes[:top_k]


