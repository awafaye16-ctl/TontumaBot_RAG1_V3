"""## 10. MMR (Maximal Marginal Relevance)

Réduit la redondance entre les chunks sélectionnés : privilégie un chunk pertinent MAIS différent de ceux déjà choisis, plutôt que plusieurs chunks très similaires entre eux.
"""

def mmr(question, candidats_ids, top_k=5, lambda_diversite=0.5):
    """
    candidats_ids : liste de chunk_id déjà présélectionnés (ex. sortie de la fusion)
    lambda_diversite : 1 = uniquement la pertinence, 0 = uniquement la diversité
    """
    if not candidats_ids:
        return []

    embedding_question = embedder.encode([question], normalize_embeddings=True)[0]
    indices_candidats = [df_chunks.index[df_chunks["chunk_id"] == cid][0] for cid in candidats_ids]
    embeddings_candidats = embeddings_chunks[indices_candidats]

    similarites_question = embeddings_candidats @ embedding_question

    selectionnes = []
    restants = list(range(len(candidats_ids)))

    while restants and len(selectionnes) < top_k:
        if not selectionnes:
            meilleur = max(restants, key=lambda i: similarites_question[i])
        else:
            def score_mmr(i):
                sim_max_selectionnes = max(
                    embeddings_candidats[i] @ embeddings_candidats[j] for j in selectionnes
                )
                return lambda_diversite * similarites_question[i] - (1 - lambda_diversite) * sim_max_selectionnes
            meilleur = max(restants, key=score_mmr)

        selectionnes.append(meilleur)
        restants.remove(meilleur)

    return [candidats_ids[i] for i in selectionnes]


