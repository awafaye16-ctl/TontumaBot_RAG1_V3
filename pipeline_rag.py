"""## 11. Filtering

Filtre les chunks selon un seuil de pertinence minimal (évite de transmettre au LLM un chunk trop faiblement lié à la question) et/ou selon des critères de métadonnées.
"""

SEUIL_SCORE_MIN = 0.01  # seuil sur le score RRF fusionné ; à ajuster selon l'échelle observée


def filtrer_chunks(candidats_ids, scores_fusion, seuil=SEUIL_SCORE_MIN, type_contenu_autorise=None):
    dict_scores = dict(scores_fusion)
    filtres = []
    for cid in candidats_ids:
        if dict_scores.get(cid, 0) < seuil:
            continue
        if type_contenu_autorise is not None:
            type_c = df_chunks.loc[df_chunks["chunk_id"] == cid, "type_contenu"].values[0]
            if type_c not in type_contenu_autorise:
                continue
        filtres.append(cid)
    return filtres


